'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {createGame}=require('./game');
const {selectMissions,record,publicView}=require('./missions');
const html=fs.readFileSync('public/index.html','utf8');
const app=fs.readFileSync('public/app.js','utf8');
const css=fs.readFileSync('public/style.css','utf8');
for(const id of ['pending-rolls','mission-announcement','yut-stage','players','board','selection-status'])assert.equal((html.match(new RegExp('id="'+id+'"','g'))||[]).length,1,'Duplicate or missing '+id);
assert(html.indexOf('id="pending-rolls"')<html.indexOf('id="mission-announcement"'));
assert(html.indexOf('id="mission-announcement"')<html.indexOf('id="yut-stage"'));
assert(html.indexOf('id="yut-stage"')<html.indexOf('id="players"'));
assert(html.indexOf('id="pending-rolls"')>html.indexOf('class="action-card"'));
assert(html.indexOf('id="pending-rolls"')>html.indexOf('id="board"'));
assert(css.includes('.mission-announcement')&&css.includes('pointer-events:none'));
assert(app.includes('missionNotifying')&&app.includes('missionEventsInitialized'));
const missions=selectMissions(2,123);
missions.common=['double_yut'];missions.secret=[['double_yut'],['back_capture']];
const game=createGame('individual',2);game.players[0].name='테스터';
const otherView=publicView(missions,1);
assert(!otherView.secret.some(x=>x.id==='double_yut'));
assert.equal(otherView.events.length,0);
record(missions,game,0,{kind:'throw',label:'윷',nak:false});
const hits=record(missions,game,0,{kind:'throw',label:'윷',nak:false});
assert(hits.some(x=>x.kind==='common'));
assert(hits.some(x=>x.kind==='secret'));
const seen=publicView(missions,1);
assert(seen.events.some(e=>e.player===0&&e.kind==='secret'&&e.title==='쌍윷'&&e.points===4&&e.serial>0));
assert.equal(new Set(seen.events.map(e=>e.serial)).size,seen.events.length);
assert.equal(seen.secret.length,1,'Uncompleted private missions remain private');
console.log('PASS UI layout order, all-player completed secret mission events, private uncompleted missions, dedup IDs');
